# critique type -> keyword heuristics (matched case-insensitively against
# the critique text). Order is the classification priority.
_CRITIQUE_KEYWORDS: dict[str, list[str]] = {
    "clarity": ["unclear", "confus", "clarif", "poorly written",
                "hard to follow", "typo", "notation", "vague",
                "rewrite", "proofread"],
    "experiments": ["experiment", "ablation", "evaluation", "dataset",
                    "empirical", "results", "analysis"],
    "baselines": ["baseline", "compar", "state-of-the-art", "sota"],
    "novelty": ["novel", "incremental", "prior work", "existing work",
                "already", "originality"],
    "significance": ["significan", "impact", "marginal",
                     "limited contribution", "motivat", "why does this matter"],
    "scope": ["scope", "narrow", "generaliz", "only", "setting", "domain"],
}

_CRITIQUE_TYPES = list(_CRITIQUE_KEYWORDS) + ["other"]


def _classify_critique(text: str) -> str:
    """Classify a critique via keyword heuristics (first match wins)."""
    low = (text or "").lower()
    for ctype, keywords in _CRITIQUE_KEYWORDS.items():
        if any(kw in low for kw in keywords):
            return ctype
    return "other"


# Response templates per critique type. Generic structure everywhere:
# acknowledge -> clarify -> evidence or commitment. They deliberately
# contain no claims of data; each reminds the user to cite only results
# they actually have.
_REBUTTAL_TEMPLATES: dict[str, str] = {
    "novelty": (
        "1. Acknowledge: thank the reviewer for engaging with the related "
        "work and restate their concern in your own words, e.g. "
        "[reviewer's specific overlap concern].\n"
        "2. Clarify: state precisely what is new in your work versus the "
        "cited prior work (different problem setting, different method, "
        "different guarantees). Point to the exact section.\n"
        "3. Evidence/commitment: cite the distinguishing experiment or "
        "argument you already have, or commit to a clearer related-work "
        "discussion in the revision. Only cite results you actually have; "
        "never invent a comparison."
    ),
    "experiments": (
        "1. Acknowledge: thank the reviewer for pushing on empirical "
        "rigor and restate what is missing, e.g. [requested experiment or "
        "analysis].\n"
        "2. Clarify: explain what the current experiments do establish, "
        "pointing to the relevant figures/tables.\n"
        "3. Evidence/commitment: either report the requested result if you "
        "already ran it, or commit to running it in the revision with a "
        "concrete plan (what data, what metric, what you expect). Never "
        "fabricate numbers."
    ),
    "clarity": (
        "1. Acknowledge: thank the reviewer for the close read and name "
        "the confusing passage, e.g. [section/figure].\n"
        "2. Clarify: give the intended reading in plain terms, in the "
        "response itself, so the reviewer sees the fix.\n"
        "3. Evidence/commitment: commit to rewriting the passage and/or "
        "adding a clarifying figure or notation table in the revision. "
        "Quote the sentence you will change if you can."
    ),
    "significance": (
        "1. Acknowledge: thank the reviewer for the frank assessment and "
        "restate their concern, e.g. [why they found it marginal].\n"
        "2. Clarify: articulate the problem's importance and who benefits, "
        "grounded in facts already in the paper or your real experience.\n"
        "3. Evidence/commitment: strengthen the motivation section and, if "
        "you have them, add concrete usage evidence. Do not invent impact."
    ),
    "baselines": (
        "1. Acknowledge: agree that strong baselines matter and restate "
        "which comparisons the reviewer wants, e.g. [missing baselines].\n"
        "2. Clarify: explain the baselines you did include and why you "
        "chose them.\n"
        "3. Evidence/commitment: add the requested comparisons if feasible, "
        "or explain precisely why a comparison is infeasible (different "
        "setting, unavailable code) and what you did instead. Never "
        "fabricate numbers; report only real results you have."
    ),
    "scope": (
        "1. Acknowledge: thank the reviewer and restate the scope concern, "
        "e.g. [narrow setting or limited generalization].\n"
        "2. Clarify: state the intended scope of the work and why that "
        "scope is a reasonable, well-defined problem.\n"
        "3. Evidence/commitment: either extend the scope in the revision if "
        "you genuinely can, or explicitly discuss the limitation and when "
        "the method would/would not apply. Do not claim generality you "
        "have not tested."
    ),
    "other": (
        "1. Acknowledge: thank the reviewer and restate their point in "
        "your own words to show you understood it.\n"
        "2. Clarify: address the substance directly, pointing to the "
        "relevant part of the paper.\n"
        "3. Evidence/commitment: say what you will change in the revision "
        "or what evidence you will add. Only promise what you can deliver."
    ),
}


def suggest_template(critique: dict | int, path: str | Path | None = None) -> str:
    """Return the response template for a critique's type.

    Accepts a critique dict (as returned by add_critique) or a critique
    id. The template is a generic acknowledge/clarify/evidence structure
    with placeholders; it invents no content for the user.
    """
    if isinstance(critique, int):
        critique = get_critique(critique, path)
    ctype = (critique or {}).get("type", "other")
    return _REBUTTAL_TEMPLATES.get(ctype, _REBUTTAL_TEMPLATES["other"])


def _load_store(path: str | Path | None = None) -> dict:
    p = Path(path) if path else REBUTTAL_PATH
    if not p.exists():
        return {"critiques": []}
    try:
        data = json.loads(p.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ResearchMapError(
            f"Rebuttal file {p} is not valid JSON: {exc}"
        ) from exc
    if not isinstance(data, dict) or not isinstance(data.get("critiques"), list):
        raise ResearchMapError(
            f"Rebuttal file {p} should contain an object with a "
            f"'critiques' list."
        )
    return data


def _save_store(store: dict, path: str | Path | None = None) -> Path:
    p = Path(path) if path else REBUTTAL_PATH
    C.ensure_data_dirs()
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(store, indent=2), encoding="utf-8")
    return p


def _next_id(store: dict) -> int:
    return max((c.get("id", 0) for c in store["critiques"]), default=0) + 1


def add_critique(text: str, path: str | Path | None = None) -> dict:
    """Add a user-supplied reviewer critique; classify it. Returns the record."""
    t = (text or "").strip()
    if not t:
        raise ResearchMapError("Critique text is empty; nothing to add.")
    store = _load_store(path)
    rec = {
        "id": _next_id(store),
        "text": t,
        "type": _classify_critique(t),
        "status": "pending",
        "draft": "",
        "date_added": date.today().isoformat(),
    }
    store["critiques"].append(rec)
    _save_store(store, path)
    return rec


def get_critique(critique_id: int, path: str | Path | None = None) -> dict:
    """Fetch one critique by id; raise if it does not exist."""
    store = _load_store(path)
    rec = next((c for c in store["critiques"] if c.get("id") == critique_id), None)
    if rec is None:
        raise ResearchMapError(
            f"No critique with id {critique_id}. Use `rebuttal list` to see ids."
        )
    return rec


def list_critiques(status: str | None = None,
                   path: str | Path | None = None) -> list[dict]:
    """List critiques, optionally filtered to 'pending' or 'addressed'."""
    if status is not None and status not in ("pending", "addressed"):
        raise ResearchMapError(
            f"Unknown status '{status}'. Choose 'pending' or 'addressed'."
        )
    critiques = _load_store(path)["critiques"]
    if status:
        critiques = [c for c in critiques if c["status"] == status]
    return sorted(critiques, key=lambda c: c["id"])


def draft_response(critique_id: int, text: str,
                   path: str | Path | None = None) -> dict:
    """Store the user's draft response on a critique. Returns the record.

    Drafting does not change the status; call mark_addressed when the
    response is final.
    """
    store = _load_store(path)
    rec = next((c for c in store["critiques"] if c.get("id") == critique_id), None)
    if rec is None:
        raise ResearchMapError(f"No critique with id {critique_id}.")
    rec["draft"] = (text or "").strip()
    _save_store(store, path)
    return rec


def mark_addressed(critique_id: int, path: str | Path | None = None) -> dict:
    """Mark a critique addressed. Returns the record."""
    store = _load_store(path)
    rec = next((c for c in store["critiques"] if c.get("id") == critique_id), None)
    if rec is None:
        raise ResearchMapError(f"No critique with id {critique_id}.")
    rec["status"] = "addressed"
    _save_store(store, path)
    return rec


def rebuttal_progress(path: str | Path | None = None) -> dict:
    """Progress stats: {"total", "addressed", "pending", "percent_addressed"}."""
    critiques = _load_store(path)["critiques"]
    addressed = sum(1 for c in critiques if c.get("status") == "addressed")
    total = len(critiques)
    return {
        "total": total,
        "addressed": addressed,
        "pending": total - addressed,
        "percent_addressed": round(100.0 * addressed / total, 1) if total else 0.0,
    }
