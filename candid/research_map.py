ENTRY_KINDS = ("project", "publication")

_RECENCY_WINDOW = 2  # years; "last 2 years" means this year + last year


def _str_list(value, field: str, idx: int) -> list[str]:
    """Normalize an entry list field: strings stay strings, deduped."""
    if value is None:
        return []
    if isinstance(value, str):
        value = [value]
    if not isinstance(value, list):
        raise ResearchMapError(
            f"Entry #{idx}: '{field}' must be a list of strings."
        )
    seen: set[str] = set()
    out: list[str] = []
    for item in value:
        s = str(item).strip()
        if s and s.lower() not in seen:
            seen.add(s.lower())
            out.append(s)
    return out


def _normalize_entry(raw: dict, idx: int) -> dict:
    """Validate one user-supplied entry and normalize it to the map schema."""
    if not isinstance(raw, dict):
        raise ResearchMapError(
            f"Entry #{idx} must be an object, got {type(raw).__name__}."
        )
    title = str(raw.get("title") or "").strip()
    if not title:
        raise ResearchMapError(f"Entry #{idx} is missing a title.")
    year = raw.get("year")
    if year is not None and year != "":
        try:
            year = int(year)
        except (TypeError, ValueError) as exc:
            raise ResearchMapError(
                f"Entry '{title}': year {year!r} is not a valid year."
            ) from exc
    else:
        year = None
    kind = str(raw.get("kind") or "project").strip().lower()
    if kind not in ENTRY_KINDS:
        raise ResearchMapError(
            f"Entry '{title}': kind must be one of "
            f"{', '.join(ENTRY_KINDS)}, got {kind!r}."
        )
    return {
        "title": title,
        "year": year,
        "kind": kind,
        "areas": _str_list(raw.get("areas"), "areas", idx),
        "claims": _str_list(raw.get("claims"), "claims", idx),
        "techniques": _str_list(raw.get("techniques"), "techniques", idx),
    }


# keyword heuristics for classifying user-stated claims (method vs
# empirical). Used only to notice a lopsided mix; the result is surfaced
# as a suggestion, never a fact.
_EMPIRICAL_CLAIM_RES = [
    r"\baccuracy\b", r"\bf1\b", r"\boutperform", r"\bimprov\w*\b",
    r"\bbenchmark", r"\bevaluat\w*\b", r"\bexperiment\w*\b",
    r"\bstate-of-the-art\b", r"\bsota\b", r"\bgain\w*\b",
    r"\breduc\w+\b", r"%\b",
]
_METHOD_CLAIM_RES = [
    r"\bnovel\b", r"\bpropos\w*\b", r"\bframework\b",
    r"\barchitecture\b", r"\balgorithm\b", r"\bdesign\w*\b",
    r"\bmethod\b", r"\bapproach\b", r"\bintroduc\w*\b",
]


def _claim_kind(claim: str) -> str:
    """Heuristically tag a user-stated claim as empirical, method, or other."""
    low = claim.lower()
    if any(re.search(p, low) for p in _EMPIRICAL_CLAIM_RES):
        return "empirical"
    if any(re.search(p, low) for p in _METHOD_CLAIM_RES):
        return "method"
    return "other"


def _suggest_label(suggestion: str) -> str:
    """Prefix every gap suggestion so it reads as a suggestion, not a fact."""
    return f"Suggestion (heuristic, not a fact): {suggestion}"


def build_map(entries: list[dict]) -> dict:
    """Build a prior-work map from user-supplied project/publication entries.

    Returns a dict with: entry_count, project/publication counts,
    timeline (chronological, undated entries last), years summary,
    area_coverage, technique_frequency, claims_index, claim_kinds, and
    gaps (see gap_observations).
    """
    normed = [_normalize_entry(e, i) for i, e in enumerate(entries or [])]

    dated = [e for e in normed if e["year"] is not None]
    undated = [e for e in normed if e["year"] is None]
    timeline = sorted(dated, key=lambda e: (e["year"], e["title"].lower()))
    timeline.extend(sorted(undated, key=lambda e: e["title"].lower()))

    by_year: dict[int, int] = {}
    for e in dated:
        by_year[e["year"]] = by_year.get(e["year"], 0) + 1

    area_coverage: dict[str, int] = {}
    for e in normed:
        for a in e["areas"]:
            area_coverage[a] = area_coverage.get(a, 0) + 1

    technique_frequency: dict[str, int] = {}
    for e in normed:
        for t in e["techniques"]:
            technique_frequency[t] = technique_frequency.get(t, 0) + 1

    claims_index: list[dict] = []
    claim_kinds = {"empirical": 0, "method": 0, "other": 0}
    for e in normed:
        for claim in e["claims"]:
            kind = _claim_kind(claim)
            claim_kinds[kind] += 1
            claims_index.append({
                "claim": claim,
                "claim_kind": kind,
                "entry": e["title"],
                "year": e["year"],
            })

    map_: dict = {
        "entry_count": len(normed),
        "projects": sum(1 for e in normed if e["kind"] == "project"),
        "publications": sum(1 for e in normed if e["kind"] == "publication"),
        "timeline": timeline,
        "years": {
            "start": min(by_year) if by_year else None,
            "end": max(by_year) if by_year else None,
            "by_year": by_year,
            "undated": len(undated),
        },
        "area_coverage": dict(
            sorted(area_coverage.items(), key=lambda kv: (-kv[1], kv[0].lower()))
        ),
        "technique_frequency": dict(
            sorted(technique_frequency.items(), key=lambda kv: (-kv[1], kv[0].lower()))
        ),
        "claims_index": claims_index,
        "claim_kinds": claim_kinds,
    }
    map_["gaps"] = gap_observations(map_)
    return map_


def gap_observations(map_: dict) -> list[dict]:
    """Heuristic gap observations over a prior-work map.

    Returns a list of {"observation", "suggestion"} dicts. Every
    suggestion is explicitly labeled as a heuristic, never a fact, and
    nothing is invented: observations only describe what the supplied
    entries do (or do not) contain.
    """
    gaps: list[dict] = []
    total = map_.get("entry_count", 0)
    timeline: list[dict] = map_.get("timeline", [])
    if total == 0:
        gaps.append({
            "observation": "The map has no entries yet.",
            "suggestion": _suggest_label(
                "Add your projects and publications (title, year, kind, "
                "areas, claims, techniques) so the map has something to organize."
            ),
        })
        return gaps

    current = date.today().year
    recent_years = {current, current - 1}

    # areas that appear only in older entries (nothing in the last 2 years)
    area_latest: dict[str, int] = {}
    for e in timeline:
        if e.get("year") is None:
            continue
        for a in e.get("areas", []):
            area_latest[a] = max(area_latest.get(a, 0), e["year"])
    for area in sorted(area_latest):
        if area_latest[area] < current - (_RECENCY_WINDOW - 1):
            gaps.append({
                "observation": (
                    f"No entries tagged '{area}' in the last "
                    f"{_RECENCY_WINDOW} years."
                ),
                "suggestion": _suggest_label(
                    f"If you are still active in {area}, add recent entries "
                    f"tagged with it; if not, the gap may simply reflect a "
                    f"shift in focus."
                ),
            })

    # claim mix: method-only vs empirical
    kinds = map_.get("claim_kinds", {})
    n_claims = len(map_.get("claims_index", []))
    if n_claims == 0:
        gaps.append({
            "observation": "No contribution claims are stated on any entry.",
            "suggestion": _suggest_label(
                "Consider writing down what you actually contributed on each "
                "entry (a method you designed, a result you measured). "
                "Only state claims that are true; never invent metrics."
            ),
        })
    elif kinds.get("empirical", 0) == 0 and kinds.get("method", 0) > 0:
        gaps.append({
            "observation": (
                "All claims are method claims; none are empirical."
            ),
            "suggestion": _suggest_label(
                "If any of your entries have measured results you can state, "
                "adding them would balance the story. Do not invent numbers; "
                "state only results you actually have."
            ),
        })

    # kind balance
    if map_.get("publications", 0) == 0:
        gaps.append({
            "observation": "No publications recorded; all entries are projects.",
            "suggestion": _suggest_label(
                "If any of this work was published, add publication entries. "
                "Otherwise the map may simply reflect unpublished work."
            ),
        })

    # undated entries
    undated = map_.get("years", {}).get("undated", 0)
    if undated:
        gaps.append({
            "observation": f"{undated} entr{'y' if undated == 1 else 'ies'} "
                           f"have no year and sit outside the timeline.",
            "suggestion": _suggest_label(
                "Fill in years where you know them so the timeline reflects "
                "the real chronology."
            ),
        })

    # technique concentration
    tech_freq: dict[str, int] = map_.get("technique_frequency", {})
    if total >= 3 and tech_freq:
        top_tech, top_n = max(tech_freq.items(), key=lambda kv: kv[1])
        if top_n / total > 0.6:
            gaps.append({
                "observation": (
                    f"'{top_tech}' appears in {top_n} of {total} entries."
                ),
                "suggestion": _suggest_label(
                    f"Heavy concentration on {top_tech} is fine if it is "
                    f"your specialty, but make sure the map also shows the "
                    f"breadth you actually have."
                ),
            })

    return gaps


def render_map(map_: dict) -> str:
    """Render a prior-work map as plain text."""
    lines = [
        f"Prior-work map: {map_.get('entry_count', 0)} entries "
        f"({map_.get('projects', 0)} projects, {map_.get('publications', 0)} publications)",
        "",
        "Timeline (chronological):",
    ]
    for e in map_.get("timeline", []):
        year = e.get("year") if e.get("year") is not None else "undated"
        areas = f" [{', '.join(e['areas'])}]" if e.get("areas") else ""
        lines.append(f"  {year}: {e['title']} ({e['kind']}){areas}")

    lines += ["", "Area coverage:"]
    coverage: dict[str, int] = map_.get("area_coverage", {})
    if coverage:
        for area, n in coverage.items():
            lines.append(f"  {area}: {n} entr{'y' if n == 1 else 'ies'}")
    else:
        lines.append("  (no areas tagged)")

    lines += ["", "Technique frequency:"]
    techs: dict[str, int] = map_.get("technique_frequency", {})
    if techs:
        for tech, n in techs.items():
            lines.append(f"  {tech}: {n}")
    else:
        lines.append("  (no techniques listed)")

    lines += ["", "Claims index:"]
    claims: list[dict] = map_.get("claims_index", [])
    if claims:
        for c in claims:
            year = f" ({c['year']})" if c.get("year") is not None else ""
            lines.append(f"  [{c['claim_kind']}] \"{c['claim']}\" - {c['entry']}{year}")
    else:
        lines.append("  (no claims stated)")

    lines += ["", "Gap observations (heuristic suggestions, not facts):"]
    gaps: list[dict] = map_.get("gaps", [])
    if gaps:
        for g in gaps:
            lines.append(f"  - {g['observation']}")
            lines.append(f"    {g['suggestion']}")
    else:
        lines.append("  (none)")
    return "\n".join(lines)


def render_map_md(map_: dict) -> str:
    """Render a prior-work map as Markdown."""
    lines = [
        "# Prior-work map",
        "",
        f"**{map_.get('entry_count', 0)} entries** "
        f"({map_.get('projects', 0)} projects, "
        f"{map_.get('publications', 0)} publications)",
        "",
        "## Timeline",
        "",
        "| Year | Title | Kind | Areas |",
        "| --- | --- | --- | --- |",
    ]
    for e in map_.get("timeline", []):
        year = str(e.get("year")) if e.get("year") is not None else "undated"
        areas = ", ".join(e.get("areas", []))
        lines.append(f"| {year} | {e['title']} | {e['kind']} | {areas} |")

    lines += ["", "## Area coverage", ""]
    coverage: dict[str, int] = map_.get("area_coverage", {})
    if coverage:
        lines += ["| Area | Entries |", "| --- | --- |"]
        for area, n in coverage.items():
            lines.append(f"| {area} | {n} |")
    else:
        lines.append("_No areas tagged._")

    lines += ["", "## Technique frequency", ""]
    techs: dict[str, int] = map_.get("technique_frequency", {})
    if techs:
        lines += ["| Technique | Entries |", "| --- | --- |"]
        for tech, n in techs.items():
            lines.append(f"| {tech} | {n} |")
    else:
        lines.append("_No techniques listed._")

    lines += ["", "## Claims index", ""]
    claims: list[dict] = map_.get("claims_index", [])
    if claims:
        for c in claims:
            year = f" ({c['year']})" if c.get("year") is not None else ""
            lines.append(
                f"- **[{c['claim_kind']}]** \"{c['claim']}\" "
                f"- *{c['entry']}*{year}"
            )
    else:
        lines.append("_No claims stated._")

    lines += ["", "## Gap observations", "",
              "_Heuristic suggestions, not facts._", ""]
    gaps: list[dict] = map_.get("gaps", [])
    if gaps:
        for g in gaps:
            lines.append(f"- **{g['observation']}**")
            lines.append(f"  - {g['suggestion']}")
    else:
        lines.append("_None._")
    return "\n".join(lines)


