"""Prior-work map and rebuttal trainer for research-oriented users.

FEATURE 1 - prior-work map
    Organize the user's research projects and publications into a
    timeline map. Input entries look like::

        {
          "title": str,          # required
          "year": int,           # optional; undated entries are kept last
          "kind": "project" | "publication",   # default "project"
          "areas": [str, ...],   # topic tags, e.g. ["nlp", "evaluation"]
          "claims": [str, ...],  # user-stated contribution claims
          "techniques": [str, ...],
        }

    build_map(entries) builds a map dict with a chronological timeline,
    area coverage, technique frequency, a claims index, and heuristic
    gap observations. render_map / render_map_md render it as text or
    Markdown. Projects can also come from the candid profile's optional
    "projects" list (load_entries falls back cleanly when it is absent).

FEATURE 2 - rebuttal trainer
    The user pastes reviewer-style critiques they received (never
    generated by candid). Each critique is classified by keyword
    heuristics, gets a response template for its type, and the user can
    draft a response and mark it addressed or pending. Critiques and
    drafts persist as JSON at candid_data/rebuttals.json (git-ignored).

Everything is local and offline: no network, no APIs, no scraping.
Nothing here invents experience, metrics, or publications. All maps
derive strictly from user-supplied entries, and every gap observation
is labeled as a heuristic suggestion, not a fact.
"""

from __future__ import annotations

import json
import re
from datetime import date
from pathlib import Path

from candid import config as C

