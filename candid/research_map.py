def load_profile_projects(profile_path: str | Path | None = None) -> list[dict]:
    """Load projects from the candid profile's optional "projects" list.

    The profile schema does not guarantee a "projects" key, so this is
    best-effort: returns [] when the profile is missing, unreadable, or
    has no projects. Never raises for a missing profile.
    """
    p = Path(profile_path) if profile_path else C.PROFILE_PATH
    if not p.exists():
        return []
    try:
        profile = json.loads(p.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return []
    projects = (profile or {}).get("projects") or []
    return projects if isinstance(projects, list) else []


def load_entries(source: list[dict] | str | Path | None = None, *,
                 profile_path: str | Path | None = None) -> list[dict]:
    """Load raw entries from a JSON file, a list of dicts, or the profile.

    - list -> returned as-is (validated later by build_map).
    - str/Path -> JSON file: either a bare list or {"entries": [...]}.
    - None -> the candid profile's "projects" list, if present; clean
      fallback to [] when the profile has none (no exception).
    """
    if isinstance(source, list):
        return source
    if isinstance(source, (str, Path)):
        p = Path(source)
        if not p.exists():
            raise ResearchMapError(f"Entries file not found: {p}")
        try:
            data = json.loads(p.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise ResearchMapError(
                f"Entries file {p} is not valid JSON: {exc}"
            ) from exc
        raw = data.get("entries") if isinstance(data, dict) else data
        if not isinstance(raw, list):
            raise ResearchMapError(
                f"Entries file {p} should contain a JSON list "
                f"(or an object with an 'entries' list)."
            )
        return raw
    return load_profile_projects(profile_path)


